  const FA_DIGITS = '۰۱۲۳۴۵۶۷۸۹';
  const digits = (lang, v) => (lang === 'en' ? String(v) : String(v).replace(/\d/g, (d) => FA_DIGITS[d]));

  // Unknown strings fall back to the Farsi text (and are logged once in the
  // browser, so a missing translation is easy to spot).
  const missing = new Set();
  function tr(lang, text, vars) {
    let out = text;
    if (lang === 'en') {
      if (Object.prototype.hasOwnProperty.call(EN, text)) out = EN[text];
      else if (typeof window !== 'undefined' && !missing.has(text)) { missing.add(text); console.warn('[i18n] missing English for:', text); }
    }
    // English plurals: { one, other }, picked by the {n} count.
    if (out && typeof out === 'object') out = vars && Number(vars.n) === 1 ? out.one : out.other;
    if (vars) {
      out = out.replace(/\{(\w+)\}/g, (m, k) => {
        if (!(k in vars)) return m;
        return typeof vars[k] === 'number' ? digits(lang, vars[k]) : String(vars[k]);
      });
    }
    return out;
  }

  const api = { EN, tr, digits };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.I18N = api;
